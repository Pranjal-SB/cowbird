def _type(schema: dict) -> str:
    if "anyOf" in schema:
        return " or ".join(_type(s) for s in schema["anyOf"])
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if schema.get("type") == "array":
        return f"array of {_type(schema.get('items', {}))}"
    return schema.get("type", "any")


def http_page() -> str:
    spec = create_app().openapi()
    schemas = spec["components"]["schemas"]
    lines = [
        STAMP,
        "# HTTP API",
        "",
        "Every route except `/health` needs an `x-api-key` header holding one of",
        "the keys in `API_KEYS`. Every response, errors included, has one shape:",
        "",
        "```json",
        '{"success": true, "data": ..., "error": null}',
        "```",
        "",
        "On an error, `success` is `false`, `data` is `null` and `error` is a",
        "fixed message. [Using cowbird from an agent](../guides/use-from-an-agent.md)",
        "lists the status codes.",
        "",
    ]
    for path, ops in spec["paths"].items():
        for method, op in ops.items():
            key = f"{method.upper()} {path}"
            if key not in ROUTES:
                sys.exit(f"gen_docs: add {key} to ROUTES")
            text, data = ROUTES[key]
            lines += [f"## `{key}`", "", text, ""]
            params = [p for p in op.get("parameters", []) if p["name"] != "x-api-key"]
            if params:
                lines += ["| Parameter | In | Type | Default |", "|---|---|---|---|"]
                for p in params:
                    s = p["schema"]
                    default = "required" if p.get("required") else _default(s.get("default"))
                    lines.append(f"| `{p['name']}` | {p['in']} | {_type(s)} | {default} |")
                lines.append("")
            body = op.get("requestBody")
            if body:
                ref = _type(body["content"]["application/json"]["schema"]).split(" or ")[0]
                model = schemas[ref]
                lines += ["JSON body:", "", "| Field | Type | Default |", "|---|---|---|"]
                for field, s in model["properties"].items():
                    required = field in model.get("required", [])
                    default = "required" if required else _default(s.get("default"))
                    lines.append(f"| `{field}` | {_type(s)} | {default} |")
                lines.append("")
            lines += ["`data` on success:", "", "```json", data, "```", ""]
    enums = [(name, s["enum"]) for name, s in sorted(schemas.items()) if "enum" in s]
    if enums:
        lines += ["## Enumerations", ""]
        lines += [f"- `{name}`: " + ", ".join(f"`{v}`" for v in values) for name, values in enums]
        lines.append("")
    return "\n".join(lines)


def settings_page() -> str:
    lines = [
        STAMP,
        "# Settings",
        "",
        "## Server",
        "",
        "`cowbird-server` reads these from the environment or from `.env` in the",
        "working directory. Names are not case-sensitive.",
        "",
        "| Variable | Default | Description |",
        "|---|---|---|",
    ]
    for name, field in Settings.model_fields.items():
        if name in DYNAMIC_DEFAULTS:
            default = DYNAMIC_DEFAULTS[name]
        elif field.default == []:
            default = "unset"
        else:
            default = _default(field.default)
        lines.append(f"| `{name.upper()}` | {default} | {SETTING_HELP.get(name, '')} |")
    lines += ["", "## Library and CLI", "", "| Variable | Default | Description |", "|---|---|---|"]
    lines += [f"| `{n}` | {d} | {h} |" for n, d, h in CORE_ENV]
    lines.append("")
    missing = set(Settings.model_fields) - set(SETTING_HELP)
    if missing:
        sys.exit(f"gen_docs: add help for new settings: {sorted(missing)}")
    return "\n".join(lines)


def _ttl(value) -> str:
    if value is None:
        return "forever"
    minutes = int(value.total_seconds() // 60)
    return f"{minutes // 60}h" if minutes % 60 == 0 and minutes >= 60 else f"{minutes}m"


def providers_page() -> str:
    classes = sorted(
        (ep.load() for ep in entry_points(group=ENTRY_POINT_GROUP)), key=lambda c: c.name
    )
    solver = sum(c.caps.needs_solver for c in classes)
    lines = [
        STAMP,
        "# Providers",
        "",
        f"{len(classes)} providers ship. {len(classes) - solver} work out of the box;",
        f"{solver} need a [Cloudflare solver](../guides/cloudflare-solver.md).",
        "Live health is not shown here: run `uv run cowbird providers`.",
        "",
        "Kinds: `own-domain` is an address on the provider's own domain;",
        "`gmail-alias` and `outlook-alias` are aliases of a real Gmail or Outlook",
        "mailbox, which many signup forms accept where a throwaway domain is refused.",
        "",
        "| Provider | Kind | Sites | Address lifetime | Push | Inbox | Needs |",
        "|---|---|---|---|---|---|---|",
    ]
    for c in classes:
        caps = c.caps
        needs = [
            n
            for n, on in (
                ("solver", caps.needs_solver),
                ("residential IP", caps.needs_residential_ip),
                ("state", caps.needs_state),
            )
            if on
        ]
        lines.append(
            f"| `{c.name}` | {', '.join(sorted(caps.kind))} | {', '.join(caps.sites)} | {_ttl(caps.address_ttl)} "
            f"| {'yes' if caps.push else 'no'} | {caps.inbox_privacy} | {', '.join(needs) or '-'} |"
        )
    lines += [
        "",
        "Inbox: `private` means only the caller can read it; `public` means anyone",
        "with the address can; `shared` means addresses come from a pool that other",
        "callers also use. Needs `state`: `cowbird wait` must be given the `state`",
        "from `cowbird new --json`.",
        "",
        "Backends that do not ship yet, and why, are in the",
        "[provider inventory](provider-inventory.md).",
        "",
    ]
    return "\n".join(lines)


PAGES = {
    "cli.md": cli_page,
    "http-api.md": http_page,
    "settings.md": settings_page,
    "providers.md": providers_page,
}


def render() -> dict[str, str]:
    return {name: build() for name, build in PAGES.items()}


def main(out: Path = OUT) -> None:
    out.mkdir(parents=True, exist_ok=True)
    for name, text in render().items():
        (out / name).write_text(text)


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else OUT)
