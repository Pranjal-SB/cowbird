def cli_page() -> str:
    parser = _parser()
    lines = [
        STAMP,
        "# CLI",
        "",
        "Every command is run as `uv run cowbird <command>` from the repo root.",
        "",
        "Exit codes: `0` success, `1` a cowbird error (printed to standard error as",
        "`error: ...`), `2` a timeout (`timeout: ...`). argparse also exits `2` on a",
        "usage error such as an unknown flag. `cowbird canary` exits `1` when any",
        "provider is quarantined, and `0` when providers are only down.",
        "",
    ]
    sub = next(a for a in parser._actions if isinstance(a, argparse._SubParsersAction))
    helps = {c.dest: c.help for c in sub._choices_actions}
    for name, cmd in sub.choices.items():
        lines += [
            f"## `cowbird {name}`",
            "",
            helps.get(name) or "",
            "",
            "```",
            cmd.format_usage().strip(),
            "```",
            "",
        ]
        rows = [a for a in cmd._actions if not isinstance(a, argparse._HelpAction)]
        if rows:
            lines += ["| Argument | Default | Description |", "|---|---|---|"]
            for a in rows:
                flag = ", ".join(a.option_strings) or a.dest
                required = a.required or not a.option_strings
                default = "required" if required else _default(a.default)
                lines.append(f"| `{flag}` | {default} | {a.help or ''} |")
            lines.append("")
    return "\n".join(lines)


def _default(value) -> str:
    if value is None:
        return "unset"
    if value is False:
        return "off"
    return f"`{json.dumps(value)}`"


